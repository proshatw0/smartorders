#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE USER ${USER_SVC_DB_USER} WITH PASSWORD '${USER_SVC_DB_PASSWORD}';
    CREATE DATABASE ${USER_SVC_DB_NAME} OWNER ${USER_SVC_DB_USER};
    \connect ${USER_SVC_DB_NAME};
    CREATE SCHEMA IF NOT EXISTS public AUTHORIZATION ${USER_SVC_DB_USER};
    GRANT ALL PRIVILEGES ON DATABASE ${USER_SVC_DB_NAME} TO ${USER_SVC_DB_USER};
EOSQL
